"""Converts the real VOLGAS logo (../pc_app/assets/volgas_logo.png - the cropped,
transparent-background VG monogram) into an RGB565 bitmap header for the
dash's ST7735 splash screen.

Composites onto black (the display's splash background) so the feathered
alpha edges from process_logo.py blend cleanly instead of showing a halo.

Run again after the source logo changes. Regenerates volgas_logo.h.
"""

from PIL import Image

SRC = "../pc_app/assets/volgas_logo.png"
OUT = "volgas_logo.h"
SIZE = 122   # fills almost the entire 128x128 display, small margin against the panel's unverified edge windowing


def to_rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


if __name__ == "__main__":
    img = Image.open(SRC).convert("RGBA").resize((SIZE, SIZE), Image.LANCZOS)
    bg = Image.new("RGB", (SIZE, SIZE), (0, 0, 0))
    bg.paste(img, (0, 0), img)

    pixels = list(bg.getdata())
    values = [to_rgb565(r, g, b) for r, g, b in pixels]

    with open(OUT, "w") as f:
        f.write("#pragma once\n")
        f.write("#include <Arduino.h>\n\n")
        f.write("// Generated by generate_logo_header.py from pc_app/assets/volgas_logo.png - do not edit by hand.\n")
        f.write(f"#define VOLGAS_LOGO_W {SIZE}\n")
        f.write(f"#define VOLGAS_LOGO_H {SIZE}\n\n")
        # const (not PROGMEM): ESP32's flash is memory-mapped, so a plain
        # const array already lives in flash (.rodata), not SRAM - unlike
        # AVR, no pgm_read_* indirection is needed to read it back.
        f.write("static const uint16_t volgas_logo[VOLGAS_LOGO_W * VOLGAS_LOGO_H] = {\n")
        for i in range(0, len(values), 16):
            row = ", ".join(str(v) for v in values[i:i + 16])
            f.write(f"  {row},\n")
        f.write("};\n")

    print(f"wrote {OUT} ({SIZE}x{SIZE}, {len(values) * 2} bytes)")
